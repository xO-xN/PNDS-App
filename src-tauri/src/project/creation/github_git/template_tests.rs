use super::*;
use crate::project::creation::git_versions_tests::{save, setup};
use crate::project::creation::tests::shared_libraries;

fn snapshot(repo: &Repository, version: &str, extra: &[u8]) -> Oid {
    let marker = serde_json::json!({ "template": "Blank", "version": version });
    template_tree(repo, Some(marker.to_string().as_bytes()), extra)
}

fn template_tree(repo: &Repository, marker: Option<&[u8]>, extra: &[u8]) -> Oid {
    let mut tree = repo.treebuilder(None).unwrap();
    if let Some(marker) = marker {
        let mut docs = repo.treebuilder(None).unwrap();
        docs.insert("template-source.json", repo.blob(marker).unwrap(), 0o100644)
            .unwrap();
        tree.insert("docs", docs.write().unwrap(), 0o040000)
            .unwrap();
    }
    tree.insert("score.txt", repo.blob(extra).unwrap(), 0o100644)
        .unwrap();
    tree.write().unwrap()
}

fn commit(repo: &Repository, tree: Oid, message: &str, parent: Option<Oid>) -> Oid {
    let signature = git2::Signature::now("Creator", "creator@example.test").unwrap();
    let parents = parent
        .map(|id| repo.find_commit(id).unwrap())
        .into_iter()
        .collect::<Vec<_>>();
    let id = repo
        .commit(
            None,
            &signature,
            &signature,
            message,
            &repo.find_tree(tree).unwrap(),
            &parents.iter().collect::<Vec<_>>(),
        )
        .unwrap();
    let head = repo.find_reference("HEAD").unwrap();
    repo.reference(head.symbolic_target().unwrap().unwrap(), id, true, message)
        .unwrap();
    id
}

#[test]
fn template_verification_accepts_a_historical_annotated_tag_and_preserves_the_project() {
    let temp = tempfile::tempdir().unwrap();
    let parent = temp.path().canonicalize().unwrap();
    let official = initialize(&parent.join("official.git"), "main", true).unwrap();
    let target = initialize(&parent.join("target.git"), "main", true).unwrap();
    let old = commit(
        &official,
        snapshot(&official, "1.6.0", b"original"),
        "old official snapshot",
        None,
    );
    official
        .tag(
            "pnds-blank-v1.6.0",
            official.find_commit(old).unwrap().as_object(),
            &git2::Signature::now("Maintainer", "maintainer@example.test").unwrap(),
            "Published Blank",
            false,
        )
        .unwrap();
    commit(
        &official,
        snapshot(&official, "1.7.0", b"new"),
        "new official snapshot",
        Some(old),
    );
    let remote_head = commit(
        &target,
        snapshot(&target, "1.6.0", b"original"),
        "generated by GitHub",
        None,
    );

    let mut access = CreationAccess::default();
    let protection = Protection::default();
    let workspace = access
        .create_blank(
            &NewProjectOptions {
                parent: parent.display().to_string(),
                folder_name: "local".into(),
                name: "Local composition".into(),
                author: String::new(),
                description: String::new(),
                locale: "en".into(),
                git_name: None,
                git_email: None,
            },
            &shared_libraries(),
            &protection,
        )
        .unwrap();
    let root = parent.join("local");
    let identity = access.open(&root, &protection).unwrap().project.identity;
    assert_eq!(workspace.project.root, root.to_string_lossy());
    fs::write(
        root.join("docs/template-source.json"),
        "edited by the creator",
    )
    .unwrap();
    save(&mut access, &identity, "Save another composition version");
    let context = access.github_context(&identity, &protection).unwrap();
    let local = context.local().unwrap();
    assert!(context
        .can_verify_template(local.head.as_deref().unwrap())
        .unwrap());
    let local_repo = Repository::open(&root).unwrap();
    let mut index = local_repo.index().unwrap();
    fs::write(root.join("server.js"), "// staged draft").unwrap();
    index.add_path(Path::new("server.js")).unwrap();
    index.write().unwrap();
    fs::write(root.join("server.js"), "// unstaged draft").unwrap();
    let index_before = fs::read(local_repo.path().join("index")).unwrap();
    let refs_before = local_repo.references().unwrap().count();
    assert_eq!(
        verify_template_repository(
            local.branch.as_deref(),
            "main",
            (target.path().to_str().unwrap(), None),
            official.path().to_str().unwrap(),
        )
        .unwrap(),
        GithubTemplateVerification::Ready {
            remote_head: remote_head.to_string(),
            template_version: "1.6.0".into(),
        }
    );
    assert_eq!(
        local_repo.head().unwrap().target().unwrap().to_string(),
        local.head.unwrap()
    );
    assert_eq!(
        fs::read(local_repo.path().join("index")).unwrap(),
        index_before
    );
    assert_eq!(
        fs::read_to_string(root.join("server.js")).unwrap(),
        "// unstaged draft"
    );
    assert_eq!(local_repo.references().unwrap().count(), refs_before);
    assert!(!local_repo.odb().unwrap().exists(remote_head));
    assert_eq!(target.head().unwrap().target(), Some(remote_head));
}

#[test]
fn template_verification_refuses_wrong_branch_modified_files_legacy_and_added_history() {
    use GithubTemplateVerification::*;

    let temp = tempfile::tempdir().unwrap();
    let official = initialize(&temp.path().join("official.git"), "main", true).unwrap();
    let target = initialize(&temp.path().join("target.git"), "main", true).unwrap();
    let published = commit(
        &official,
        snapshot(&official, "1.7.0", b"published content"),
        "published",
        None,
    );
    official
        .tag_lightweight(
            "pnds-blank-v1.7.0",
            official.find_commit(published).unwrap().as_object(),
            false,
        )
        .unwrap();
    let target_url = target.path().to_str().unwrap();
    let official_url = official.path().to_str().unwrap();
    let verify = |local_branch, default_branch| {
        verify_template_repository(
            local_branch,
            default_branch,
            (target_url, None),
            official_url,
        )
        .unwrap()
    };
    let cases = [
        (template_tree(&target, None, b"old layout"), LegacyTemplate),
        (
            template_tree(&target, Some(b"malformed"), b"published content"),
            SnapshotMismatch,
        ),
        (
            snapshot(&target, "1.7.0", b"modified content"),
            SnapshotMismatch,
        ),
        (
            snapshot(&target, "1.7.1", b"unpublished version"),
            SnapshotMismatch,
        ),
    ];
    for (tree, expected) in cases {
        let root = commit(&target, tree, "generated", None);
        assert_eq!(verify(Some("main"), "main"), expected);
        assert_eq!(target.head().unwrap().target(), Some(root));
    }
    let tree = snapshot(&target, "1.7.0", b"published content");
    let root = commit(&target, tree, "generated", None);
    target
        .reference("refs/heads/other", root, false, "test branch")
        .unwrap();
    assert_eq!(verify(Some("other"), "main"), BranchMismatch);
    assert_eq!(verify(Some("other"), "other"), RemoteHistoryChanged);
    assert_eq!(
        verify(Some("main"), "main"),
        Ready {
            remote_head: root.to_string(),
            template_version: "1.7.0".into(),
        }
    );
    let extra = commit(&target, tree, "added an empty commit", Some(root));
    assert_eq!(verify(Some("main"), "main"), RemoteHistoryChanged);
    assert_eq!(target.head().unwrap().target(), Some(extra));
}

#[test]
fn template_verification_eligibility_follows_the_original_blank_source() {
    for (source, eligible) in [
        ("PNDS App embedded blank-project", true),
        ("PNDS GitHub Blank template", false),
    ] {
        let (_temp, root, mut access, identity) = setup();
        let marker = root.join("docs/template-source.json");
        fs::create_dir(root.join("docs")).unwrap();
        let provenance = |source| {
            serde_json::json!({ "template": "Blank", "version": "1.6.0", "source": source })
                .to_string()
        };
        fs::write(&marker, provenance(source)).unwrap();
        save(&mut access, &identity, "Initial version");
        fs::write(
            &marker,
            provenance(if eligible {
                "edited"
            } else {
                "PNDS App embedded blank-project"
            }),
        )
        .unwrap();
        let head = save(&mut access, &identity, "Save an edited project");
        let context = access
            .github_context(&identity, &Protection::default())
            .unwrap();
        assert_eq!(context.can_verify_template(&head).unwrap(), eligible);
    }
}
