//! SynthDef compile runner (v1.2.0, issue #17).
//!
//! Process adapter for the trusted creation workflow. Loads the caller's
//! standard source set with local sclang and the existing .add/writeDefFile
//! wrapper, writing into caller-owned staging. The creation capability owns
//! manifest checks and final artifact publication.
//!
//! The sclang side runs [`RUNNER_SCRIPT`], a static wrapper validated against
//! SuperCollider 3.14 whose argv is `<synthdefs-dir> <source.scd>…`. All
//! functions here are path-based (no AppHandle). Project validation and
//! publication belong to creation/compile.rs; CI uses substitute executables.

use std::fs;
use std::os::unix::process::CommandExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::{Duration, Instant};

/// The standard macOS SuperCollider install location, checked before PATH.
const STANDARD_SCLANG: &str = "/Applications/SuperCollider.app/Contents/MacOS/sclang";

/// Where the class-library compile banner ends and real output starts.
const SCLANG_BANNER_END: &str = "*** Welcome to SuperCollider";

/// The sclang program the App generates into a temp dir and executes. Kept
/// verbatim from the SuperCollider 3.14 validation run — the quirks it works
/// around are noted inline and any edit needs re-validation against a real
/// sclang.
const RUNNER_SCRIPT: &str = r#"// PNDS SynthDef compile runner — generated by the PNDS App developer tools.
//
// Usage: sclang <this-file> <synthdefs-dir> <source.scd> [...more.scd]
//
// Loads every source file (sources register SynthDefs with `.add`), then
// writes each newly registered SynthDef to <synthdefs-dir>/<defName>.scsyndef,
// enforcing: SynthDef name = artifact file name = manifest reference.
(
var outDir = thisProcess.argv[0];
var sources = thisProcess.argv.copyToEnd(1);
var failures = List.new;
var fresh = Set.new;
var baseline;
var exitCode = 1;

// All failures become data; the single bare exit at the end reports them.
// (`N.exit` is only reliable as the final bare statement — nested or
// non-Integer receivers silently misfire or hang the REPL.)
try {
    File.mkdir(outDir);
    baseline = SynthDescLib.global.synthDescs.keys.as(Set);
    sources.do { |src|
        // `executeFile` can post errors without ever throwing, so sources
        // are compiled explicitly: a nil compile result is a failure.
        var func = this.compileFile(src);
        if(func.isNil) {
            ("error: " ++ src ++ " did not compile").postln;
            failures.add(src);
        } {
            // try's handler also runs when the body returns nil — end with
            // `true` so only real throws reach the handler.
            var ok = try { func.value; true } { |error|
                ("error in " ++ src ++ ": " ++ error.errorString).postln;
                false
            };
            if(ok.not) { failures.add(src) };
        };
    };
    if(failures.isEmpty) {
        fresh = SynthDescLib.global.synthDescs.keys.as(Set) - baseline;
        if(fresh.isEmpty) {
            "error: the source files registered no SynthDefs (use SynthDef('name', { ... }).add)".postln;
            failures.add("no-new-synthdefs");
        } {
            fresh.do { |name|
                var def = SynthDescLib.global.at(name).def;
                if(def.isNil) {
                    ("error: SynthDef " ++ name ++ " cannot be written (no definition object)").postln;
                    failures.add(name.asString);
                } {
                    def.writeDefFile(outDir);
                    ("wrote " ++ name.asString ++ ".scsyndef").postln;
                };
            };
        };
    };
} { |error|
    ("runner error: " ++ error.errorString).postln;
    error.reportError;
    failures.add("runner");
};

if(failures.isEmpty) { exitCode = 0 };
exitCode.exit;
)
"#;

/// Locates `sclang`: the standard macOS app install first, then the PATH.
pub fn find_sclang() -> Result<PathBuf, String> {
    find_sclang_with(PathBuf::from(STANDARD_SCLANG), std::env::var_os("PATH"))
}

/// Testable core of [`find_sclang`] — the standard-path candidate and the
/// PATH value are injected.
fn find_sclang_with(
    standard: PathBuf,
    path_env: Option<std::ffi::OsString>,
) -> Result<PathBuf, String> {
    if standard.is_file() {
        return Ok(standard);
    }
    if let Some(paths) = path_env {
        for dir in std::env::split_paths(&paths) {
            let candidate = dir.join("sclang");
            if candidate.is_file() {
                return Ok(candidate);
            }
        }
    }
    Err(
        "SuperCollider was not found. Install it from https://supercollider.github.io/downloads \
         (the compile tool uses its bundled sclang), or make the `sclang` command available on \
         your PATH."
            .to_string(),
    )
}

/// Runs the existing .add/writeDefFile wrapper with a caller-owned output directory.
/// The creation workflow stages output before publishing it through its capability.
pub(super) fn run_sclang(
    root: &Path,
    sources: &[PathBuf],
    synthdefs_dir: &Path,
    sclang: &Path,
    timeout: Duration,
    cancelled: &AtomicBool,
) -> Result<String, String> {
    if cancelled.load(Ordering::Acquire) {
        return Err("SynthDef compilation cancelled".into());
    }
    let staging =
        tempfile::tempdir().map_err(|e| format!("Failed to create the staging directory: {e}"))?;
    let wrapper = staging.path().join("pnds-compile.scd");
    fs::write(&wrapper, RUNNER_SCRIPT)
        .map_err(|e| format!("Failed to write the compile script: {e}"))?;

    let mut child = Command::new(sclang)
        .arg(&wrapper)
        .arg(synthdefs_dir)
        .args(sources)
        .current_dir(root)
        // sclang falls into an interactive REPL when its script aborts —
        // with stdin closed it EOFs out instead of hanging forever.
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .process_group(0)
        .spawn()
        .map_err(|e| format!("Failed to start {}: {e}", sclang.display()))?;

    // Drain both pipes on reader threads so a chatty sclang can never block
    // on a full pipe buffer.
    let stdout_handle = spawn_reader(child.stdout.take());
    let stderr_handle = spawn_reader(child.stderr.take());

    let started = Instant::now();
    let status = loop {
        if cancelled.load(Ordering::Acquire) {
            break Err("SynthDef compilation cancelled".into());
        }
        match child.try_wait() {
            Ok(Some(status)) => break Ok(status),
            Ok(None) => {
                if started.elapsed() > timeout {
                    break Err(format!(
                        "sclang did not finish within {} seconds and was terminated — \
                         SuperCollider may be showing a dialog or waiting for input.",
                        timeout.as_secs()
                    ));
                }
                std::thread::sleep(Duration::from_millis(50));
            }
            Err(e) => break Err(format!("Failed to wait for sclang: {e}")),
        }
    };
    // Sources can launch child processes. Close the entire compile group,
    // including inherited pipes, before joining readers on every exit path.
    unsafe {
        libc::kill(-(child.id() as i32), libc::SIGKILL);
    }
    let _ = child.kill();
    let _ = child.wait();
    let stdout = stdout_handle.join().unwrap_or_default();
    let stderr = stderr_handle.join().unwrap_or_default();
    let status =
        status.map_err(|error| format!("{error}\n\n{}", sclang_output(&stdout, &stderr)))?;

    if !status.success() {
        let code = status.code().unwrap_or(-1);
        return Err(format!(
            "SynthDef compilation failed (sclang exit code {code}).\n\n{}",
            sclang_output(&stdout, &stderr)
        ));
    }

    Ok(sclang_output(&stdout, &stderr))
}

/// Reads a child pipe to EOF on a background thread, returning UTF-8 lossy
/// text (sclang output is text; invalid sequences must not lose the rest).
fn spawn_reader(
    mut pipe: Option<impl std::io::Read + Send + 'static>,
) -> std::thread::JoinHandle<String> {
    std::thread::spawn(move || {
        let Some(pipe) = pipe.as_mut() else {
            return String::new();
        };
        let mut text = Vec::new();
        let mut buffer = [0u8; 8 * 1024];
        loop {
            match pipe.read(&mut buffer) {
                Ok(0) | Err(_) => break,
                Ok(n) => {
                    text.extend_from_slice(&buffer[..n]);
                    if text.len() > 1024 * 1024 {
                        text.drain(..text.len() - 1024 * 1024);
                    }
                }
            }
        }
        String::from_utf8_lossy(&text).into_owned()
    })
}

/// Composes the sclang output for an error: stdout (where sclang prints its
/// errors — its stderr is usually empty) with the class-library banner
/// trimmed, then stderr when present.
fn sclang_output(stdout: &str, stderr: &str) -> String {
    let mut out = trim_sclang_banner(stdout).trim().to_string();
    let err = stderr.trim();
    if !err.is_empty() {
        if !out.is_empty() {
            out.push_str("\n\n");
        }
        out.push_str(err);
    }
    out
}

/// Drops everything up to and including the `*** Welcome to SuperCollider`
/// line so error text starts at the first real message.
fn trim_sclang_banner(output: &str) -> String {
    if let Some(pos) = output.find(SCLANG_BANNER_END) {
        if let Some(newline) = output[pos..].find('\n') {
            return output[pos + newline + 1..].to_string();
        }
    }
    output.to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    #[test]
    fn find_sclang_prefers_standard_path_then_path_fallback() {
        let dir = tempfile::tempdir().unwrap();
        let standard = dir.path().join("SuperCollider.app/MacOS/sclang");
        fs::create_dir_all(standard.parent().unwrap()).unwrap();
        fs::write(&standard, "").unwrap();

        assert_eq!(find_sclang_with(standard.clone(), None).unwrap(), standard);

        // Standard missing → first PATH hit wins.
        let bin = dir.path().join("bin");
        fs::create_dir_all(&bin).unwrap();
        fs::write(bin.join("sclang"), "").unwrap();
        let missing = dir.path().join("nowhere/sclang");
        let path_env = Some(
            std::env::join_paths([
                dir.path().join("empty-dir"),
                bin.clone(),
                dir.path().join("also-empty"),
            ])
            .unwrap(),
        );
        assert_eq!(
            find_sclang_with(missing.clone(), path_env).unwrap(),
            bin.join("sclang")
        );

        // Nothing anywhere → the install guidance.
        let err = find_sclang_with(missing, None).unwrap_err();
        assert!(err.contains("supercollider.github.io"), "unexpected: {err}");
        assert!(err.contains("PATH"), "unexpected: {err}");
    }

    #[test]
    fn trim_sclang_banner_keeps_output_without_the_marker() {
        assert_eq!(trim_sclang_banner("plain output"), "plain output");
        let noisy = "compiling class library...\ncompile done\n*** Welcome to SuperCollider 3.14.1. ***\nERROR: boom\ncleanup";
        assert_eq!(trim_sclang_banner(noisy), "ERROR: boom\ncleanup");
    }
}
